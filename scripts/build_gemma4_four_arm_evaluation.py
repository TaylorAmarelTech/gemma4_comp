#!/usr/bin/env python3
"""Build a four-arm Gemma 4 adapter and deterministic-harness study.

The four arms are the frozen base model without the harness, the same base
response with a deterministic review harness, the trained Low-Rank Adaptation
adapter without the harness, and the same adapted response with the harness.
The harness wraps model text as an unverified draft; it does not validate or
endorse the draft.  Egregious examples are selected from recorded DueCare
benchmark responses and retain prompt, response, model, arm, and judge lineage.
No free-standing fictional response is generated by this study.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import shutil
import time
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RUNNER_PATH = ROOT / "scripts" / "run_gemma4_local_adapter_experiment.py"
DEFAULT_RUN = ROOT / "reports" / "training_runs" / "gemma4_e2b_grounded_adapter_v3"
DEFAULT_OUTPUT = DEFAULT_RUN / "four_arm_study"
DEFAULT_EGREGIOUS_RANKINGS = ROOT / "reports" / "egregious_ranker.jsonl"
DEFAULT_RICH_RESULTS = ROOT / "reports" / "rich_lift" / "results.jsonl"
SCHEMA = "duecare.gemma4.four_arm_study.v2"
MARKER = ".duecare-four-arm-study"


class StudyError(RuntimeError):
    """Raised when source evidence cannot support a reproducible study."""


def _load_runner():
    spec = importlib.util.spec_from_file_location("duecare_gemma4_runner", RUNNER_PATH)
    if not spec or not spec.loader:
        raise StudyError(f"cannot import experiment runner: {RUNNER_PATH}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


RUNNER = _load_runner()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _read_json(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise StudyError(f"expected a JSON object: {path}")
    return value


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    return list(_iter_jsonl(path))


def _iter_jsonl(path: Path) -> Iterable[dict[str, Any]]:
    with path.open(encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            if not line.strip():
                continue
            value = json.loads(line)
            if not isinstance(value, dict):
                raise StudyError(f"expected an object at {path}:{number}")
            yield value


def _write_json(path: Path, value: Any) -> None:
    path.write_text(
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def _write_jsonl(path: Path, rows: Iterable[Mapping[str, Any]]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")


def _prepare_output(path: Path, *, force: bool) -> Path:
    path = path.resolve()
    if path.exists():
        if not force:
            raise StudyError(f"output already exists; use --force: {path}")
        if not (path / MARKER).is_file():
            raise StudyError(f"refusing to replace unowned directory: {path}")
        shutil.rmtree(path)
    path.mkdir(parents=True)
    (path / MARKER).write_text(SCHEMA + "\n", encoding="utf-8")
    return path


def _text_sha256(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def recorded_egregious_examples(
    rankings_path: Path,
    results_path: Path,
    *,
    limit: int = 6,
    subject_model: str = "gemma4:31b",
    allow_partial: bool = False,
) -> list[dict[str, Any]]:
    """Join actual ranked failures to recorded baseline and harness responses.

    With ``allow_partial=True`` the join returns every complete recorded pair
    up to ``limit`` instead of failing when fewer qualify; at least one pair is
    still required so an empty study can never be silently prepared.
    """
    if limit <= 0:
        raise StudyError("egregious example limit must be positive")
    rankings = [
        row
        for row in _read_jsonl(rankings_path.resolve(strict=True))
        if float(row.get("egregiousness") or 0.0) >= 8.0
        and str(row.get("model") or "") == subject_model
    ]
    rankings.sort(
        key=lambda row: (-float(row.get("egregiousness") or 0.0), str(row.get("prompt_id") or ""))
    )
    ranked: dict[str, dict[str, Any]] = {}
    for row in rankings:
        prompt_id = str(row.get("prompt_id") or "")
        if prompt_id and prompt_id not in ranked:
            ranked[prompt_id] = row
    if len(ranked) < limit and not allow_partial:
        raise StudyError(
            f"only {len(ranked)} recorded egregious prompts met the ranking contract"
        )

    arms: dict[str, dict[str, dict[str, Any]]] = {prompt_id: {} for prompt_id in ranked}
    # The rich-lift result ledger can approach a gigabyte. Stream until every
    # selected prompt has both arms instead of materializing the full file.
    for row in _iter_jsonl(results_path.resolve(strict=True)):
        prompt_id = str(row.get("prompt_id") or "")
        if prompt_id not in arms or str(row.get("model") or "") != subject_model:
            continue
        arm = str(row.get("arm") or "")
        if arm in {"baseline", "harness_full"}:
            arms[prompt_id][arm] = row
    selected = [
        (prompt_id, rank)
        for prompt_id, rank in ranked.items()
        if {"baseline", "harness_full"} <= set(arms[prompt_id])
    ][:limit]
    if len(selected) < limit and not allow_partial:
        raise StudyError(
            f"only {len(selected)} ranked prompts have complete recorded response pairs"
        )
    if not selected:
        raise StudyError("no ranked prompts have complete recorded response pairs")

    output: list[dict[str, Any]] = []
    for index, (prompt_id, rank) in enumerate(selected, 1):
        pair = arms[prompt_id]
        baseline = str(pair["baseline"].get("response") or "")
        harnessed = str(pair["harness_full"].get("response") or "")
        prompt = str(pair["baseline"].get("prompt_text") or "")
        if not baseline or not harnessed or not prompt:
            raise StudyError(f"recorded response pair is empty for {prompt_id}")
        output.append(
            {
                "fixture_id": f"recorded-{index:02d}",
                "failure_type": str(rank.get("harm_type") or "recorded_harmful_response"),
                "prompt_id": prompt_id,
                "prompt": prompt,
                "subject_model": subject_model,
                "egregiousness_score": float(rank.get("egregiousness") or 0.0),
                "judge_rationale": rank.get("why"),
                "worst_quote": rank.get("worst_quote"),
                "egregious_response": baseline,
                "bounded_rewrite": harnessed,
                "prompt_sha256": _text_sha256(prompt),
                "baseline_response_sha256": _text_sha256(baseline),
                "harness_response_sha256": _text_sha256(harnessed),
                "provenance": "recorded DueCare benchmark response pair; no fictional generation",
                "training_eligible": False,
            }
        )
    return output


def build_study(
    run_dir: Path,
    output_dir: Path,
    *,
    force: bool,
    rankings_path: Path = DEFAULT_EGREGIOUS_RANKINGS,
    rich_results_path: Path = DEFAULT_RICH_RESULTS,
) -> dict[str, Any]:
    run_dir = run_dir.resolve(strict=True)
    run_manifest_path = run_dir / "run-manifest.json"
    run_manifest = _read_json(run_manifest_path)
    if run_manifest.get("adapter_produced") is not True:
        raise StudyError("source run did not produce an adapter")
    evaluation_decl = ((run_manifest.get("artifacts") or {}).get("evaluation") or {})
    evaluation_path = run_dir / str(evaluation_decl.get("path") or "")
    if not evaluation_path.is_file() or _sha256(evaluation_path) != evaluation_decl.get(
        "sha256"
    ):
        raise StudyError("source evaluation failed manifest verification")
    source_rows = _read_jsonl(evaluation_path)
    output_dir = _prepare_output(output_dir, force=force)

    study_rows: list[dict[str, Any]] = []
    arm_keys = (
        "base_without_harness",
        "base_with_harness",
        "adapter_without_harness",
        "adapter_with_harness",
    )
    for source in source_rows:
        base = str((source.get("base") or {}).get("response") or "")
        adapted = str((source.get("adapted") or {}).get("response") or "")
        texts = {
            "base_without_harness": base,
            "base_with_harness": RUNNER.apply_review_harness(base),
            "adapter_without_harness": adapted,
            "adapter_with_harness": RUNNER.apply_review_harness(adapted),
        }
        arms = {
            key: {
                "text": texts[key],
                "score": RUNNER.score_response(texts[key]),
                "origin": (
                    "model generated"
                    if "without_harness" in key
                    else "deterministic harness transformed"
                ),
            }
            for key in arm_keys
        }
        study_rows.append(
            {
                "id": source.get("id"),
                "source_row_id": source.get("source_row_id"),
                "source_lineage_family_id": source.get("source_lineage_family_id"),
                "prompt": source.get("prompt"),
                "reference": source.get("reference"),
                "arms": arms,
            }
        )

    def mean_score(arm: str) -> float:
        return round(
            sum(row["arms"][arm]["score"]["objective_score"] for row in study_rows)
            / len(study_rows),
            6,
        )

    means = {arm: mean_score(arm) for arm in arm_keys}
    effects = {
        "adapter_effect_without_harness": round(
            means["adapter_without_harness"] - means["base_without_harness"], 6
        ),
        "harness_effect_on_base": round(
            means["base_with_harness"] - means["base_without_harness"], 6
        ),
        "harness_effect_on_adapter": round(
            means["adapter_with_harness"] - means["adapter_without_harness"], 6
        ),
    }
    effects["adapter_harness_interaction"] = round(
        effects["harness_effect_on_adapter"] - effects["harness_effect_on_base"],
        6,
    )
    summary = {
        "schema_version": SCHEMA,
        "rows": len(study_rows),
        "mean_objective_score_by_arm": means,
        "effects": effects,
        "interpretation_boundary": (
            "The harness demonstrates deterministic response bounding, not factual "
            "validation. Adapter lift remains limited to this tiny grounded-remix holdout."
        ),
        "not_demonstrated": [
            "real-world effectiveness",
            "legal correctness",
            "independent safety improvement",
            "production readiness",
        ],
    }
    rows_path = output_dir / "four-arm-evaluation.jsonl"
    failures_path = output_dir / "recorded-egregious-examples.jsonl"
    summary_path = output_dir / "four-arm-summary.json"
    _write_jsonl(rows_path, study_rows)
    egregious_rows = recorded_egregious_examples(rankings_path, rich_results_path)
    _write_jsonl(failures_path, egregious_rows)
    _write_json(summary_path, summary)
    manifest = {
        "schema_version": SCHEMA,
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "source_run_manifest_sha256": _sha256(run_manifest_path),
        "source_evaluation_sha256": _sha256(evaluation_path),
        "egregious_rankings_sha256": _sha256(rankings_path),
        "rich_results_sha256": _sha256(rich_results_path),
        "arms": list(arm_keys),
        "summary": summary,
        "artifacts": {
            path.name: {"bytes": path.stat().st_size, "sha256": _sha256(path)}
            for path in (rows_path, failures_path, summary_path)
        },
    }
    manifest_path = output_dir / "four-arm-manifest.json"
    _write_json(manifest_path, manifest)
    return {
        "output_dir": str(output_dir),
        "manifest_sha256": _sha256(manifest_path),
        **summary,
    }


def parser() -> argparse.ArgumentParser:
    value = argparse.ArgumentParser(description=__doc__)
    value.add_argument("--run-dir", type=Path, default=DEFAULT_RUN)
    value.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    value.add_argument("--egregious-rankings", type=Path, default=DEFAULT_EGREGIOUS_RANKINGS)
    value.add_argument("--rich-results", type=Path, default=DEFAULT_RICH_RESULTS)
    value.add_argument("--force", action="store_true")
    return value


def main(argv: Sequence[str] | None = None) -> int:
    args = parser().parse_args(argv)
    print(
        json.dumps(
            build_study(
                args.run_dir,
                args.output_dir,
                force=args.force,
                rankings_path=args.egregious_rankings,
                rich_results_path=args.rich_results,
            ),
            indent=2,
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
