from __future__ import annotations

import json
from pathlib import Path

PATH = Path("packages/duecare-llm-chat/src/duecare/chat/harness/_examples.json")


def main() -> None:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    existing_ids = {p.get("id") for p in data}
    new_prompts = _new_prompts()
    to_add = [p for p in new_prompts if p["id"] not in existing_ids]
    if not to_add:
        print("All v0.9.0 prompts already present.")
        return
    data.extend(to_add)
    PATH.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n",
                       encoding="utf-8")
    print(f"Added {len(to_add)} prompts.")
    print(f"Total prompt count: {len(data)}")


